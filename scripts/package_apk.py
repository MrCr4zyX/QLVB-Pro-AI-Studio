#!/usr/bin/env python3
import os
import sys
import shutil
import tempfile
import zipfile
import subprocess
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
DIST_DIR = BASE_DIR / "dist"
PUBLIC_DIR = BASE_DIR / "public"
KEYSTORE_PATH = BASE_DIR / "scripts" / "debug.keystore"
COMPILED_DEX = BASE_DIR / "scripts" / "classes.dex"
FRAMEWORK_RES = Path("/usr/share/android-framework-res/framework-res.apk")

MANIFEST_XML = """<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    package="com.k02.qlvbpro"
    android:versionCode="199"
    android:versionName="19.9">

    <uses-sdk
        android:minSdkVersion="22"
        android:targetSdkVersion="32" />

    <uses-permission android:name="android.permission.INTERNET" />
    <uses-permission android:name="android.permission.ACCESS_NETWORK_STATE" />
    <uses-permission android:name="android.permission.READ_EXTERNAL_STORAGE" />
    <uses-permission android:name="android.permission.WRITE_EXTERNAL_STORAGE" />
    <uses-permission android:name="android.permission.VIBRATE" />
    <uses-permission android:name="android.permission.POST_NOTIFICATIONS" />

    <application
        android:allowBackup="true"
        android:requestLegacyExternalStorage="true"
        android:icon="@mipmap/ic_launcher"
        android:label="QLVB PRO"
        android:roundIcon="@mipmap/ic_launcher"
        android:supportsRtl="true"
        android:theme="@android:style/Theme.DeviceDefault.NoActionBar">
        <activity
            android:name="com.k02.qlvbpro.MainActivity"
            android:exported="true"
            android:launchMode="singleTask"
            android:configChanges="orientation|keyboardHidden|keyboard|screenSize|locale|smallestScreenSize|screenLayout|uiMode">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data
                    android:scheme="k02qlvb"
                    android:host="auth" />
            </intent-filter>
        </activity>
    </application>
</manifest>
"""

def ensure_keystore():
    if not KEYSTORE_PATH.exists():
        print(f"Creating persistent Android debug keystore at {KEYSTORE_PATH}...")
        subprocess.run([
            "keytool", "-genkeypair", "-v",
            "-keystore", str(KEYSTORE_PATH),
            "-alias", "androiddebugkey",
            "-keyalg", "RSA", "-keysize", "2048", "-validity", "10000",
            "-storepass", "android", "-keypass", "android",
            "-dname", "CN=Android Debug,O=Android,C=US"
        ], check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return KEYSTORE_PATH

def main():
    if not DIST_DIR.exists():
        print("dist directory does not exist. Run npm run build first.")
        sys.exit(1)

    smali_dir = BASE_DIR / "scripts" / "smali"
    if shutil.which("smali") and smali_dir.exists():
        print("Assembling classes.dex from scripts/smali...")
        subprocess.run(["smali", "assemble", str(smali_dir), "-o", str(COMPILED_DEX)], check=True)

    if not COMPILED_DEX.exists():
        print("Error: scripts/classes.dex not found.")
        sys.exit(1)

    if not FRAMEWORK_RES.exists():
        print("Error: framework-res.apk not found. Install android-framework-res.")
        sys.exit(1)

    keystore = ensure_keystore()
    logo_src = PUBLIC_DIR / "pwa-192x192.png"
    if not logo_src.exists():
        logo_src = PUBLIC_DIR / "app-logo.png"

    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_path = Path(tmpdir)
        manifest_file = tmp_path / "AndroidManifest.xml"
        manifest_file.write_text(MANIFEST_XML, encoding="utf-8")

        res_dir = tmp_path / "res"
        for density in ["mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"]:
            density_dir = res_dir / f"mipmap-{density}"
            density_dir.mkdir(parents=True, exist_ok=True)
            shutil.copy(logo_src, density_dir / "ic_launcher.png")

        base_apk = tmp_path / "base.apk"
        cmd_aapt = [
            "aapt", "package", "-f",
            "-M", str(manifest_file),
            "-S", str(res_dir),
            "-I", str(FRAMEWORK_RES),
            "-F", str(base_apk)
        ]
        print("Compiling Android manifest & resources with aapt...")
        subprocess.run(cmd_aapt, check=True)

        # Read base APK generated by aapt
        apk_files = {}
        with zipfile.ZipFile(base_apk, "r") as z:
            for item in z.infolist():
                apk_files[item.filename] = z.read(item.filename)

        # Add classes.dex
        apk_files["classes.dex"] = COMPILED_DEX.read_bytes()

        # Add dist web assets
        for root, _, files in os.walk(DIST_DIR):
            for file in files:
                full_path = Path(root) / file
                rel_path = full_path.relative_to(DIST_DIR).as_posix()
                if rel_path.endswith((".apk", ".zip", ".idsig")) or rel_path.startswith("assets/aistudio/"):
                    continue
                apk_files[f"assets/dist/{rel_path}"] = full_path.read_bytes()

        raw_apk = tmp_path / "raw.apk"
        aligned_apk = tmp_path / "aligned.apk"

        # Pack into unaligned archive
        with zipfile.ZipFile(raw_apk, "w", compression=zipfile.ZIP_DEFLATED) as z:
            for name in sorted(apk_files.keys()):
                data = apk_files[name]
                compress = zipfile.ZIP_STORED if name.endswith((".png", ".ico", ".arsc", ".jpg", ".mp4")) else zipfile.ZIP_DEFLATED
                z.writestr(name, data, compress_type=compress)

        # 4-byte zipalign
        print("Running zipalign -f -p 4...")
        subprocess.run(["zipalign", "-f", "-p", "4", str(raw_apk), str(aligned_apk)], check=True)

        # Official apksigner with V1 + V2 + V3
        print("Signing APK with official apksigner (V1 + V2 + V3)...")
        subprocess.run([
            "apksigner", "sign",
            "--ks", str(keystore),
            "--ks-key-alias", "androiddebugkey",
            "--ks-pass", "pass:android",
            "--key-pass", "pass:android",
            "--v1-signing-enabled", "true",
            "--v2-signing-enabled", "true",
            "--v3-signing-enabled", "true",
            str(aligned_apk)
        ], check=True)

        # Verify signature
        print("Verifying APK signature:")
        verify_proc = subprocess.run(
            ["apksigner", "verify", "-v", str(aligned_apk)],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True
        )
        print(verify_proc.stdout)
        if verify_proc.returncode != 0:
            print(f"Signature verification failed: {verify_proc.stderr}")
            sys.exit(1)

        # Verify badging
        print("Verifying APK badging:")
        badging_proc = subprocess.run(
            ["aapt", "dump", "badging", str(aligned_apk)],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True
        )
        for line in badging_proc.stdout.splitlines()[:6]:
            print(f"  {line}")

        final_apk_data = aligned_apk.read_bytes()
        print(f"Successfully generated signed APK. Size: {len(final_apk_data)} bytes")

        # Remove older versioned APKs so /public/ stays clean with 19.9
        for old_apk in [
            PUBLIC_DIR / "k02_mobile_qlvb_19.8.apk",
            PUBLIC_DIR / "k02_mobile_qlvb_19.7.apk",
            PUBLIC_DIR / "k02_mobile_qlvb_19.6.apk",
            PUBLIC_DIR / "k02_mobile_qlvb_19.5.apk",
            PUBLIC_DIR / "k02_mobile_qlvb_19.4.apk",
            PUBLIC_DIR / "k02_mobile_qlvb_19.3.apk",
            PUBLIC_DIR / "k02_mobile_qlvb_19.2.apk",
            PUBLIC_DIR / "k02_mobile_qlvb_19.1.apk",
            PUBLIC_DIR / "k02_mobile_qlvb_1.9.apk",
            DIST_DIR / "k02_mobile_qlvb_19.8.apk",
            DIST_DIR / "k02_mobile_qlvb_19.7.apk",
            DIST_DIR / "k02_mobile_qlvb_19.6.apk",
            DIST_DIR / "k02_mobile_qlvb_19.5.apk",
            DIST_DIR / "k02_mobile_qlvb_19.4.apk",
            DIST_DIR / "k02_mobile_qlvb_19.3.apk",
            DIST_DIR / "k02_mobile_qlvb_19.2.apk",
            DIST_DIR / "k02_mobile_qlvb_19.1.apk",
            DIST_DIR / "k02_mobile_qlvb_1.9.apk",
        ]:
            if old_apk.exists():
                old_apk.unlink()

        outputs = [
            PUBLIC_DIR / "k02_mobile_qlvb_19.9.apk",
            PUBLIC_DIR / "k02_mobile_qlvb.apk",
            DIST_DIR / "k02_mobile_qlvb_19.9.apk",
            DIST_DIR / "k02_mobile_qlvb.apk",
        ]
        for out in outputs:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(final_apk_data)
            print(f"-> Wrote {out.relative_to(BASE_DIR)} ({len(final_apk_data)} bytes)")

        # Create updated k02_web_html.zip
        web_zip_path = PUBLIC_DIR / "k02_web_html.zip"
        with zipfile.ZipFile(web_zip_path, "w", compression=zipfile.ZIP_DEFLATED) as z:
            for root, _, files in os.walk(DIST_DIR):
                for file in files:
                    full_p = Path(root) / file
                    if full_p.suffix in (".apk", ".zip", ".idsig"):
                        continue
                    rel_p = full_p.relative_to(DIST_DIR).as_posix()
                    z.write(full_p, rel_p)
        print(f"-> Wrote {web_zip_path.relative_to(BASE_DIR)} ({web_zip_path.stat().st_size} bytes)")
        dist_web_zip = DIST_DIR / "k02_web_html.zip"
        dist_web_zip.write_bytes(web_zip_path.read_bytes())

    print("\n[SUCCESS] APK v19.9 compiled with official aapt, aligned & signed successfully!")

if __name__ == "__main__":
    main()
